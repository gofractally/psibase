#!/usr/bin/env python3
"""Build native wallet components from a source snapshot excluding concurrent work."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tarfile
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build-native-wallet"
SOURCE = BUILD / "source"
OVERLAYS = ("packages/user/Exchange", "packages/user/Tokens/plugin", "packages/user/Tokens/query-service",
            "packages/user/Tokens/ui", "packages/system/Transact/plugin",
            "packages/user/Permissions/plugin", "packages/user/Supervisor/ui",
            "packages/user/Host/plugin/prompt")
PLATFORM = ("host-client", "host-db", "host-http", "host-types", "host-prompt",
            "host-crypto", "host-auth", "host-accounts", "auth-any", "auth-sig",
            "accounts", "accounts-query", "login-prompt", "clientdata", "permissions",
            "aes", "kdf", "base64", "web-crypto", "transact", "transact-admin", "invite")


def prepare():
    BUILD.mkdir(exist_ok=True)
    head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    marker = BUILD / "source-head"
    if not marker.exists() or marker.read_text().strip() != head:
        shutil.rmtree(SOURCE, ignore_errors=True)
        SOURCE.mkdir()
        with tempfile.TemporaryFile() as archive:
            subprocess.run(["git", "archive", "--format=tar", head], cwd=ROOT,
                           stdout=archive, check=True)
            archive.seek(0)
            with tarfile.open(fileobj=archive) as tar:
                tar.extractall(SOURCE, filter="data")
        marker.write_text(head + "\n")
    for relative in OVERLAYS:
        shutil.copytree(ROOT / relative, SOURCE / relative, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns("target", "node_modules", "__pycache__"))
    manifest = SOURCE / "packages/user/Cargo.toml"
    text = manifest.read_text()
    if '"Exchange/plugin"' not in text:
        text = text.replace("members = [", 'members = [\n    "Exchange/plugin",', 1)
        manifest.write_text(text)
    files = [p for relative in OVERLAYS for p in (ROOT / relative).rglob("*")
             if p.is_file() and p.suffix in (".rs", ".wit", ".toml", ".js", ".mjs", ".ts", ".tsx", ".mts", ".html", ".css")
             and p.name != "bindings.rs"
             and not any(part in ("target", "node_modules", "dist") for part in p.parts)]
    (BUILD / "source.json").write_text(json.dumps({
        "base_commit": head,
        "workspace": "Committed manifests plus Exchange/plugin only; unrelated bridge workspace members excluded; current shared SDK source overlaid",
        "generated_bindings": "Regenerated by cargo-component from the recorded WIT; excluded from handwritten input hashes",
        "files": {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(files)},
    }, indent=2) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("prepare", "platform", "user", "compat"))
    args = parser.parse_args()
    if args.operation == "prepare":
        prepare()
        print(SOURCE)
        return
    if not SOURCE.exists():
        raise SystemExit("Run prepare once after source freeze before component builds")
    if args.operation == "compat":
        for workspace, package in (("packages/system", "credentials-plugin"),
                                   ("packages/system", "virtual-server-plugin"),
                                   ("packages/user", "name-market-plugin")):
            subprocess.run(["cargo", "component", "build", "--release", "--target-dir",
                            str(BUILD / "compat"), "-p", f"{package}@0.29.0"],
                           cwd=SOURCE / workspace, env=os.environ, check=True)
        return
    workspace = "packages" if args.operation == "platform" else "packages/user"
    packages = PLATFORM if args.operation == "platform" else ("tokens-plugin", "exchange-plugin")
    command = ["cargo", "component", "build", "--release", "--target-dir",
               str(BUILD / args.operation)]
    for package in packages:
        command += ["-p", f"{package}@0.29.0"]
    raise SystemExit(subprocess.call(command, cwd=SOURCE / workspace, env=os.environ))


if __name__ == "__main__":
    main()
