#!/usr/bin/env python3
"""Generate every runtime action-name table/vector from one saved model.

  python3 tools/action_names.py generate
  python3 tools/action_names.py check
  python3 tools/action_names.py import-training --bundle experiments/method-names/action-name-training
  python3 tools/action_names.py update request.json --apply

Training updates are bounded by the saved development policy. Consumers never
need editing when the model changes: regenerate, rebuild, and run conformance.
"""
import argparse
import hashlib
import json
from pathlib import Path
import random
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
RESEARCH = ROOT / 'experiments/method-names'
sys.path.insert(0, str(RESEARCH))
from action_name_model import canonical_json, load_model, encode_name, decode_name, ALPHABET
import benchmark

MODEL = ROOT / 'libraries/psibase/common/share/action-name-model.json'
DEFAULT_BUNDLE = RESEARCH / 'action-name-training'
MANIFEST = ROOT / 'tools/action_names.generated.json'


def digest(raw):
    return hashlib.sha256(raw).hexdigest()


def string(value):
    return json.dumps(value, ensure_ascii=True).replace('\\u0000', '\\0')


def trie(words):
    nodes = [{'children': {}, 'token': 0}]
    for token, word in enumerate(words[1:], 1):
        node = 0
        for char in word:
            if char not in nodes[node]['children']:
                nodes[node]['children'][char] = len(nodes)
                nodes.append({'children': {}, 'token': 0})
            node = nodes[node]['children'][char]
        nodes[node]['token'] = token
    rows, edges = [], []
    for node in nodes:
        rows.append((len(edges), len(node['children']), node['token']))
        edges.extend(sorted(node['children'].items()))
    return rows, edges


def render(document):
    loaded = load_model(document)
    model_hash = loaded.model_sha256
    char = document['character']['cdf_rows']
    words = document['word']['symbols']
    cdf = document['word']['cdf']
    costs = document['word']['token_costs']
    nodes, edges = trie(words)
    cpp = ['// Generated by tools/action_names.py; do not edit.', '// clang-format off', '#pragma once',
           '#include <cstdint>', '#include <string_view>', 'namespace psio::detail::action_name_data {',
           f'inline constexpr char model_sha256[] = "{model_hash}";',
           f'inline constexpr char format_version[] = "{document["format_version"]}";',
           'inline constexpr std::uint16_t character_cdf[1407][39] = {']
    cpp += ['  {' + ','.join(map(str, row)) + '},' for row in char]
    cpp += ['};', 'inline constexpr std::string_view words[] = {']
    cpp += ['  ' + string(word if index else '') + ',' for index, word in enumerate(words)]
    cpp += ['};', 'inline constexpr std::uint16_t word_cdf[] = {' + ','.join(map(str, cdf)) + '};',
            'inline constexpr std::uint32_t word_costs[] = {' + ','.join(map(str, costs)) + '};',
            'struct TrieNode { std::uint32_t first_edge; std::uint16_t edge_count; std::uint16_t token; };',
            'struct TrieEdge { char character; std::uint32_t next; };',
            'inline constexpr TrieNode word_nodes[] = {']
    cpp += ['  {' + ','.join(map(str, row)) + '},' for row in nodes]
    cpp += ['};', 'inline constexpr TrieEdge word_edges[] = {']
    cpp += [f"  {{'{char}',{child}}}," for char, child in edges]
    cpp += ['};', '} // namespace psio::detail::action_name_data', '']
    rust = ['// Generated by tools/action_names.py; do not edit.',
            f'pub const MODEL_SHA256: &str = "{model_hash}";',
            f'pub const FORMAT_VERSION: &str = "{document["format_version"]}";',
            '#[rustfmt::skip]', 'pub const CHAR_CDF: [[u16; 39]; 1407] = [']
    rust += ['  [' + ','.join(map(str, row)) + '],' for row in char]
    rust += ['];', '#[rustfmt::skip]', 'pub const WORDS: &[&str] = &[']
    rust += ['  ' + string(word) + ',' for word in words]
    rust += ['];', '#[rustfmt::skip]', 'pub const WORD_CDF: &[u16] = &[' + ','.join(map(str, cdf)) + '];',
             '#[rustfmt::skip]', 'pub const WORD_COSTS: &[u32] = &[' + ','.join(map(str, costs)) + '];', '']
    js = ['// Generated by tools/action_names.py; do not edit.',
          f'export const ACTION_NAME_MODEL_SHA256 = "{model_hash}";',
          f'export const ACTION_NAME_FORMAT_VERSION = "{document["format_version"]}";',
          '// prettier-ignore', 'export const CHARACTER_CDFS: ReadonlyArray<ReadonlyArray<number>> = [']
    js += ['  [' + ','.join(map(str, row)) + '],' for row in char]
    js += ['];', '// prettier-ignore', 'export const WORD_SYMBOLS: ReadonlyArray<string> = ' + json.dumps(words) + ';',
           '// prettier-ignore', 'export const WORD_CDF: ReadonlyArray<number> = ' + json.dumps(cdf) + ';',
           '// prettier-ignore', 'export const WORD_COSTS: ReadonlyArray<number> = ' + json.dumps(costs) + ';', '']
    names = set()
    evaluation = DEFAULT_BUNDLE / 'inputs/evaluation.json'
    if evaluation.exists():
        for values in json.loads(evaluation.read_text())['groups'].values():
            names.update(values)
    names.update(row['method'] for row in benchmark.local_methods())
    names.update(['a', 'Z', '_', 'getUint32', 'getInt32', 'foo_bar', 'fooqbar', 'regEvIdx',
                  'requestRecovery', 'registerEventIndex', 'sx', 'szziat', 'o0_l1', 'x' * 256,
                  '#c000000000000000', '#ffffffffffffffff'])
    for index in range(300):
        rng = random.Random(index)
        names.add(rng.choice('abcdefghijklmnopqrstuvwxyz_') + ''.join(rng.choices(ALPHABET, k=index % 80)))
    vectors = []
    for name in sorted(names):
        value = encode_name(loaded, name)
        decoded = decode_name(loaded, value)
        assert encode_name(loaded, decoded) == value
        vectors.append({'text': name, 'value_u64': str(value), 'decoded': decoded})
    invalid = ['', '0get', 'foo-bar', 'get.data', 'get data', 'é', 'x' * 257, '#short',
               '#C000000000000000', '#0000000000000000', '#c00000000000000g']
    for name in invalid:
        try:
            encode_name(loaded, name)
        except ValueError:
            continue
        raise ValueError(f'Invalid vector accepted by reference: {name}')
    vectors_doc = {'format_version': document['format_version'], 'model_sha256': model_hash,
                   'vectors': vectors, 'invalid_names': invalid,
                   'invalid_u64_decimal': ['-1', '18446744073709551616', '0']}
    result = {
        'libraries/psio/include/psio/detail/action_name_data.hpp': '\n'.join(cpp).encode(),
        'rust/psibase_names/src/action_name_model.generated.rs': '\n'.join(rust).encode(),
        'packages/user/CommonApi/common/packages/common-lib/src/action-name-model.generated.ts': '\n'.join(js).encode(),
        'libraries/psibase/common/share/action-name-vectors.json': canonical_json(vectors_doc) + b'\n',
    }
    manifest = {'format_version': document['format_version'], 'model_sha256': model_hash,
                'model_file_sha256': digest(MODEL.read_bytes()), 'vectors': len(vectors),
                'generated': {path: digest(data) for path, data in result.items()}}
    result[str(MANIFEST.relative_to(ROOT))] = canonical_json(manifest) + b'\n'
    return result


def generate(check=False):
    document = json.loads(MODEL.read_text())
    release_lock = DEFAULT_BUNDLE / 'release.lock'
    if release_lock.exists():
        locked = json.loads(release_lock.read_text())
        if locked['model_sha256'] != load_model(document).model_sha256:
            raise ValueError('Runtime model differs from the release-locked training model')
    result = render(document)
    stale = []
    for relative, raw in result.items():
        path = ROOT / relative
        if check:
            if not path.exists() or path.read_bytes() != raw:
                stale.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
    if stale:
        raise ValueError('Stale generated action-name artifacts: ' + ', '.join(stale))
    print(json.dumps({'checked' if check else 'generated': len(result),
                      'model_sha256': load_model(document).model_sha256}))


def report():
    loaded = load_model(json.loads(MODEL.read_text()))
    names = sorted({row['method'] for row in benchmark.local_methods()})
    modes, fallbacks = {str(mode): 0 for mode in range(4)}, []
    for name in names:
        value = encode_name(loaded, name)
        modes[str(value >> 62)] += 1
        if value >> 62 == 3:
            fallbacks.append(name)
    print(json.dumps({'model_sha256': loaded.model_sha256, 'current_core_names': len(names),
                      'readable': len(names) - len(fallbacks), 'mode_counts': modes,
                      'hash_fallback_names': fallbacks}, indent=2))


def import_training(bundle):
    import action_name_training as training
    revision, manifest = training.verify_pack(bundle)
    source = training.revision_path(bundle, revision) / 'model.json'
    MODEL.parent.mkdir(parents=True, exist_ok=True)
    MODEL.write_bytes(source.read_bytes())
    generate()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('generate')
    sub.add_parser('check')
    sub.add_parser('report')
    command = sub.add_parser('import-training')
    command.add_argument('--bundle', type=Path, default=DEFAULT_BUNDLE)
    command = sub.add_parser('update')
    command.add_argument('request', type=Path)
    command.add_argument('--bundle', type=Path, default=DEFAULT_BUNDLE)
    command.add_argument('--apply', action='store_true')
    args = parser.parse_args()
    try:
        if args.command == 'generate': generate()
        elif args.command == 'check': generate(True)
        elif args.command == 'report': report()
        elif args.command == 'import-training': import_training(args.bundle)
        else:
            command = [sys.executable, str(RESEARCH / 'action_name_training.py'), 'update', str(args.bundle), str(args.request)]
            if args.apply: command.append('--apply')
            subprocess.run(command, check=True)
            if args.apply: import_training(args.bundle)
    except (ValueError, OSError, subprocess.CalledProcessError) as error:
        parser.exit(2, str(error) + '\n')


if __name__ == '__main__':
    main()
